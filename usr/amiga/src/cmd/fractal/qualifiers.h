#define QUALIFIERS_RIGHT_BUTTON		(0x2000)
#define QUALIFIERS_LEFT_BUTTON		(0x4000)
#define QUALIFIERS_BUTTON		(QUALIFIERS_LEFT_BUTTON   | \
