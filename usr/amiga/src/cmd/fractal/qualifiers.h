#define QUALIFIERS_RIGHT_COMMAND	(0x0080)
#define QUALIFIERS_COMMAND		(QUALIFIERS_LEFT_COMMAND | \
					 QUALIFIERS_RIGHT_COMMAND)
#define QUALIFIERS_LEFT_AMIGA		(QUALIFIERS_LEFT_COMMAND)
#define QUALIFIERS_RIGHT_AMIGA		(QUALIFIERS_RIGHT_COMMAND)
